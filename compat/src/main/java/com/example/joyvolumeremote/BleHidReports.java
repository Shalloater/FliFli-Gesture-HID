package com.example.joyvolumeremote;

import java.util.Arrays;

/** HOGP carries the report ID in the Report Reference descriptor, not in the payload. */
final class BleHidReports {
    static final int KEYBOARD_ID = 1;
    static final int CONSUMER_ID = 2;
    static final byte[] REPORT_MAP = {
            0x05, 0x01, 0x09, 0x06, (byte) 0xA1, 0x01, (byte) 0x85, 0x01,
            0x05, 0x07, 0x19, (byte) 0xE0, 0x29, (byte) 0xE7, 0x15, 0x00, 0x25, 0x01,
            0x75, 0x01, (byte) 0x95, 0x08, (byte) 0x81, 0x02,
            0x75, 0x08, (byte) 0x95, 0x01, (byte) 0x81, 0x01,
            0x19, 0x00, 0x2A, (byte) 0x81, 0x00, 0x15, 0x00, 0x26, (byte) 0x81, 0x00,
            0x75, 0x08, (byte) 0x95, 0x06, (byte) 0x81, 0x00,
            0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x15, 0x00, 0x25, 0x01,
            0x75, 0x01, (byte) 0x95, 0x05, (byte) 0x91, 0x02,
            0x75, 0x03, (byte) 0x95, 0x01, (byte) 0x91, 0x01, (byte) 0xC0,
            0x05, 0x0C, 0x09, 0x01, (byte) 0xA1, 0x01, (byte) 0x85, 0x02,
            0x15, 0x00, 0x26, (byte) 0xFF, 0x03, 0x19, 0x00, 0x2A, (byte) 0xFF, 0x03,
            0x75, 0x10, (byte) 0x95, 0x01, (byte) 0x81, 0x00, (byte) 0xC0
    };

    static byte[] keyboard(int modifiers, int[] usages) {
        byte[] result = new byte[8];
        result[0] = (byte) modifiers;
        if (usages != null) {
            for (int i = 0; i < Math.min(6, usages.length); i++) result[i + 2] = (byte) usages[i];
        }
        return result;
    }

    static byte[] consumer(int usage) {
        return new byte[]{(byte) usage, (byte) (usage >> 8)};
    }

    static byte[] atOffset(byte[] value, int offset) {
        if (offset < 0 || offset > value.length) return null;
        return Arrays.copyOfRange(value, offset, value.length);
    }

    private BleHidReports() {}
}
